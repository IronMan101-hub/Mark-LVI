"""Exposes GALAHAD plugins to the existing MARK LVI tool loader (plugins/galahad_*.py).

Each bridge file is ~5 lines: `PLUGIN, run = bridge.make("galahad_productivity")`. The tool
declarations are read from galahad/catalog.json (generated by `python -m galahad catalog`),
so launching the desktop app does not import every GALAHAD plugin just to describe it.
"""
from __future__ import annotations

import json
from pathlib import Path

CATALOG = Path(__file__).with_name("catalog.json")

# Tool name -> (what it is for, plugin ids). Names are prefixed so they cannot collide with MARK LVI tools.
GROUPS: dict[str, tuple[str, list[str]]] = {
    "galahad_productivity": ("Tasks, reminders (recurring too), calendar events and the daily briefing. Prefer this over the plain `reminder` tool when the user wants a recurring/persistent reminder, a task list, a deadline or a briefing.", ["productivity"]),
    "galahad_media": ("Spotify (official API) and YouTube: play/pause/skip/volume/search/playlists/now-playing.", ["spotify", "youtube"]),
    "galahad_comms": ("Gmail (read/search/summarise/draft/send), WhatsApp drafts/sends, Instagram navigation. Sending always waits for the user's on-screen confirmation.", ["gmail", "whatsapp", "instagram"]),
    "galahad_office": ("Word (.docx), Excel (.xlsx) and PowerPoint (.pptx): create, read, edit, calculate, chart, save. Never overwrites without confirmation.", ["word", "excel", "powerpoint"]),
    "galahad_intel": ("News in 7 categories (medicine, science, ai_tech, finance, economics, india, international), briefings, saved articles, and multi-source deep research with citations.", ["news", "research"]),
    "galahad_finance": ("Personal finance tracker (expenses, income, budgets, goals, FD/RD/SIP holdings), market quotes and FX. Needs the user to grant the finance permission.", ["finance"]),
    "galahad_system": ("Safeguarded file search/organise/delete, app launch/close with verification, window control, volume, clipboard, screenshots, system monitor, and unified search across everything.", ["files", "computer", "sysmon", "search", "utilities"]),
    "galahad_browser": ("Web search results, reading/summarising/comparing pages, and tab control in the GALAHAD-controlled browser.", ["browser"]),
    "galahad_core": ("Workflows/automation, long-term memory (remember/recall/forget), activity log, notifications, screen/image understanding, AI provider settings.", ["automation", "assistant", "vision", "ai_providers"]),
}
UNTRUSTED = {"browser", "gmail", "news", "research", "word", "powerpoint", "excel", "youtube", "instagram", "whatsapp", "vision"}


def _catalog() -> dict:
    try:
        return json.loads(CATALOG.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _sig(c: dict) -> str:
    ps = ",".join(f"{k}{'*' if v.get('required') else ''}" for k, v in c["params"].items())
    return f"{c['plugin']}.{c['command']}({ps})"


def declaration(name: str) -> dict:
    desc, plugins = GROUPS[name]
    cat = _catalog()
    lines = []
    for pid in plugins:
        for c in cat.get(pid, []):
            lines.append(f"{_sig(c)}: {c['description'].split('. ')[0][:90]}")
    full = (f"{desc} Call with plugin, command and arguments (a JSON object as text, only the listed parameter names; * = required). "
            "Commands marked as needing confirmation will put a prompt on screen — never claim they happened until the result says done. "
            "Commands:\n" + "\n".join(lines))
    return {"name": name, "description": full[:9000],
            "parameters": {"type": "OBJECT", "properties": {
                "plugin": {"type": "STRING", "description": "One of: " + ", ".join(plugins)},
                "command": {"type": "STRING", "description": "Command name exactly as listed"},
                "arguments": {"type": "STRING", "description": 'JSON object text, e.g. {"title":"Buy milk","due":"tomorrow 5pm"}'}},
                "required": ["plugin", "command"]},
            "brief": desc[:160]}


def _parse_args(raw) -> dict:
    if isinstance(raw, dict):
        return raw
    if not raw:
        return {}
    try:
        v = json.loads(raw)
        return v if isinstance(v, dict) else {}
    except (TypeError, ValueError):
        raise ValueError("arguments must be a JSON object")


def make(name: str):
    desc, plugins = GROUPS[name]
    decl = declaration(name)
    meta = {"name": decl["name"], "description": decl["description"], "parameters": decl["parameters"], "tier": "extra", "brief": decl["brief"]}

    def run(parameters: dict, player=None, session_memory=None) -> str:
        try:
            from core import outcome
        except Exception:            # running outside the desktop app (tests, CLI)
            outcome = None
        pid, cmd = str(parameters.get("plugin", "")).strip(), str(parameters.get("command", "")).strip()
        try:
            if pid not in plugins:
                raise ValueError(f"plugin must be one of: {', '.join(plugins)}")
            args = _parse_args(parameters.get("arguments"))
            from .engine import get_engine
            eng = get_engine()
            if player is not None and eng.player is None:
                eng.player = player
            res = eng.registry.execute(pid, cmd, args, origin="voice")
        except Exception as e:  # noqa: BLE001 — a tool must never raise
            return outcome.failed(name, str(e)) if outcome else f"Sir, that didn't work: {e}"
        text = (res.message or "")[:2500]
        if res.status == "awaiting_confirmation":
            _surface_confirmation(eng, res, player)
            if outcome:
                return outcome.ask(name, "Please confirm on screen.", detail=text[:200])
            return f"Confirmation needed on screen: {text}. Do not claim it is done."
        if not outcome:
            return text if res.ok else f"Sir, that failed: {text}"
        if res.ok:
            head = outcome.done(name, plugin=pid, command=cmd)
            return head + "\n" + (outcome.untrusted(f"{pid}.{cmd}", text) if pid in UNTRUSTED else text)
        return outcome.failed(name, text or "failed", plugin=pid, command=cmd)

    return meta, run


def _surface_confirmation(eng, res, player) -> None:
    """Also show the HUD banner so a voice user can approve without the dashboard."""
    try:
        from core import confirm
        pend = eng.confirmations.get(res.pending_id)
        if pend:
            lines = pend.summary.splitlines()
            confirm.request(f"galahad-{pend.id}", lines[0][:60], "\n".join(lines[1:])[:300] or pend.summary[:300],
                            lambda pid=pend.id: eng.registry.approve(pid).message)
    except Exception:
        pass


def build_catalog(engine) -> dict:
    """Compact on purpose: only what a tool description needs."""
    out: dict = {}
    for c in engine.registry.catalog():
        out.setdefault(c["plugin"], []).append({
            "plugin": c["plugin"], "command": c["command"], "description": c["description"].split(". ")[0][:110],
            "params": {k: {"required": bool(v.get("required"))} for k, v in c["params"].items()}})
    return out
